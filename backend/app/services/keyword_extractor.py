"""
Keyword Extractor — Deterministic ATS keyword scoring engine.

This module handles Layer 1 of the hybrid ATS scoring system:
1. Extracts technical keywords from job descriptions (not soft skills)
2. Converts LaTeX resumes to searchable plain text
3. Matches JD keywords against resume text with synonym normalization
4. Calculates a deterministic score using a fixed formula

The score is NEVER generated by an LLM — it's pure Python math.

Scoring Formula:
    keyword_score     = (matched_required / total_required) * 60     [0-60]
    preferred_score   = (matched_preferred / total_preferred) * 20   [0-20]
    ai_quality_score  = LLM provides this (experience alignment)     [0-20]
    ---------------------------------------------------------------
    final_score       = keyword_score + preferred_score + ai_quality_score

Hard Penalties (applied after sum):
    - Domain mismatch (resume is in a completely unrelated field):  -20
    - Experience gap (each year short of JD requirement):          -10 per year
    - Final score clamped to [0, 100]
"""

