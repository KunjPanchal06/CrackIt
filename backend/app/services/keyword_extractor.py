def latex_to_plain_text(latex_code: str) -> str:
    """
    Convert LaTeX source code to searchable plain text.

    Strips LaTeX commands, preamble, environments, and formatting
    while preserving the actual text content that an ATS would see.
    """
    text = latex_code

    # Remove comments (lines starting with %)
    text = re.sub(r'%.*$', '', text, flags=re.MULTILINE)

    # Remove documentclass and usepackage declarations
    text = re.sub(r'\\documentclass\b[^{]*\{[^}]*\}', '', text)
    text = re.sub(r'\\usepackage\b[^{]*\{[^}]*\}', '', text)

    # Remove preamble-only commands (consume the rest of their line)
    text = re.sub(
        r'\\(?:pagestyle|thispagestyle|setlength|setcounter|newcommand|'
        r'renewcommand|def|geometry|hypersetup|titleformat|titlespacing|'
        r'pagenumbering|addtolength|input|include)\b[^\n]*',
        '', text
    )

    # Remove \begin{...} and \end{...} environment markers
    text = re.sub(r'\\(?:begin|end)\{[^}]*\}', '', text)

    # Convert text-formatting commands to their content:
    # \textbf{content} -> content, \emph{content} -> content, etc.
    text = re.sub(
        r'\\(?:textbf|textit|textsc|emph|underline|textnormal|mbox)\{([^}]*)\}',
        r'\1', text
    )

    # \href{url}{display text} -> display text
    text = re.sub(r'\\href\{[^}]*\}\{([^}]*)\}', r'\1', text)

    # \section{Title} -> Title  (preserve heading text)
    text = re.sub(
        r'\\(?:section|subsection|subsubsection)\*?\{([^}]*)\}',
        r'\1', text
    )

    # Remove \item markers, keep the bullet text that follows
    text = re.sub(r'\\item\b\s*', ' ', text)

    # Remove all remaining LaTeX commands (\commandname or \commandname*)
    text = re.sub(r'\\[a-zA-Z]+\*?', ' ', text)

    # Remove braces and brackets
    text = re.sub(r'[{}\[\]]', ' ', text)

    # Remove special LaTeX characters
    text = re.sub(r'[~$&#^_]', ' ', text)

    # Remove stray backslashes
    text = re.sub(r'\\', ' ', text)

    # Normalize whitespace
    text = re.sub(r'\s+', ' ', text).strip()

    return text


def extract_keywords_from_jd(
    job_description: str,
) -> tuple[list[str], list[str]]:
    """
    Extract technical keywords from a job description and classify
    them as 'required' or 'preferred'.

    Strategy:
    1. Scan the JD text for known tech terms (from TECH_KEYWORDS set)
    2. Use regex to catch multi-word patterns (e.g. "React Native")
    3. Classify based on proximity to required/preferred signal phrases
    4. Filter out soft skills
    5. Deduplicate using canonical synonym forms

    Returns:
        (required_keywords, preferred_keywords) — both lists of
        canonical, lowercased keyword strings.
    """
    jd_lower = job_description.lower()

    # -- Step 1: Find all tech keywords present in the JD --
    found_keywords: set[str] = set()

    # Check multi-word terms first (longest match priority)
    sorted_tech = sorted(TECH_KEYWORDS, key=len, reverse=True)

    for term in sorted_tech:
        if len(term.split()) > 1:
            # Multi-word: substring match
            if term in jd_lower:
                found_keywords.add(_get_canonical(term))
        else:
            # Single word: word boundary to avoid "Java" matching "JavaScript"
            if re.search(r'\b' + re.escape(term) + r'\b', jd_lower):
                found_keywords.add(_get_canonical(term))

    # Also check canonical synonym map keys + their synonyms
    for canonical, synonyms in SYNONYM_MAP.items():
        canon_lower = canonical.lower()
        if _term_in_text(canon_lower, jd_lower):
            found_keywords.add(canon_lower)
        for syn in synonyms:
            if _term_in_text(syn.lower(), jd_lower):
                found_keywords.add(canon_lower)

    # -- Step 2: Remove soft skills --
    found_keywords = {kw for kw in found_keywords if kw not in SOFT_SKILLS}

    # -- Step 3: Classify into required vs preferred --
    required: list[str] = []
    preferred: list[str] = []

    for kw in found_keywords:
        if _classify_keyword(kw, jd_lower) == "preferred":
            preferred.append(kw)
        else:
            required.append(kw)

    # Sort for deterministic output
    required.sort()
    preferred.sort()

    return required, preferred


def match_keywords_against_resume(
    keywords: list[str],
    resume_plain_text: str,
) -> tuple[list[str], list[str]]:
    """
    Check which JD keywords are present in the resume plain text.
    Uses synonym normalization so "React.js" matches "React", etc.

    Returns:
        (matched, missing) — two lists of keyword strings.
    """
    resume_lower = resume_plain_text.lower()
    matched: list[str] = []
    missing: list[str] = []

    for kw in keywords:
        if _keyword_found_in_text(kw, resume_lower):
            matched.append(kw)
        else:
            missing.append(kw)

    return matched, missing


def calculate_deterministic_score(
    matched_required: int,
    total_required: int,
    matched_preferred: int,
    total_preferred: int,
    ai_quality_score: int,
    domain_mismatch: bool,
    experience_gap_years: int,
) -> tuple[int, dict]:
    """
    Calculate the final ATS score using a fixed, deterministic formula.

    This function is the ONLY place the final score is computed.
    The LLM never sets the score — only provides the quality_score input.

    Formula:
        keyword_score   = (matched_required / total_required) * 60
        preferred_score = (matched_preferred / total_preferred) * 20
        quality_score   = ai_quality_score (clamped to 0-20)
        raw_score       = keyword_score + preferred_score + quality_score

    Penalties:
        - domain_mismatch:  -20
        - experience_gap:   -10 per year short

    Returns:
        (final_score, breakdown_dict)
    """
    # -- Component scores --
    if total_required > 0:
        keyword_score = round((matched_required / total_required) * 60)
    else:
        keyword_score = 60  # No required keywords extracted -> full credit

    if total_preferred > 0:
        preferred_score = round((matched_preferred / total_preferred) * 20)
    else:
        preferred_score = 20  # No preferred keywords -> full credit

    quality_score = max(0, min(20, ai_quality_score))

    # -- Raw total --
    raw_score = keyword_score + preferred_score + quality_score

    # -- Hard penalties --
    penalty = 0
    if domain_mismatch:
        penalty += 20
    if experience_gap_years > 0:
        penalty += experience_gap_years * 10

    final_score = max(0, min(100, raw_score - penalty))

    # -- Breakdown for the frontend --
    breakdown = {
        "keyword_score": keyword_score,
        "keyword_max": 60,
        "preferred_score": preferred_score,
        "preferred_max": 20,
        "quality_score": quality_score,
        "quality_max": 20,
        "raw_score": raw_score,
        "domain_penalty": -20 if domain_mismatch else 0,
        "experience_penalty": -(experience_gap_years * 10) if experience_gap_years > 0 else 0,
        "total_penalty": -penalty,
        "final_score": final_score,
    }

    return final_score, breakdown


def parse_experience_gap(experience_gap_str: str) -> int:
    """
    Parse the LLM's experience_gap string to extract how many years
    the candidate is short.

    Examples:
        "JD requires 5 years, resume shows 2 — 3 years short" -> 3
        "none" -> 0
        "No experience gap detected" -> 0
    """
    if not experience_gap_str:
        return 0

    gap_lower = experience_gap_str.lower().strip()

    # Explicit "none" / "no gap"
    if gap_lower in ("none", "n/a", "no gap", "0"):
        return 0
    if "no experience gap" in gap_lower or "no gap" in gap_lower:
        return 0
    if "meets" in gap_lower or "exceeds" in gap_lower:
        return 0

    # Pattern: "X year(s) short"
    match = re.search(r'(\d+)\s*year[s]?\s*short', gap_lower)
    if match:
        return int(match.group(1))

    # Pattern: two year numbers -> compute difference
    # e.g., "requires 5 years, resume shows 2"
    numbers = re.findall(r'(\d+)\s*(?:\+\s*)?year', gap_lower)
    if len(numbers) >= 2:
        required_years = int(numbers[0])
        actual_years = int(numbers[1])
        return max(0, required_years - actual_years)

    # Single number with gap language
    if "short" in gap_lower or "less" in gap_lower or "gap" in gap_lower:
        numbers = re.findall(r'(\d+)', gap_lower)
        if numbers:
            return int(numbers[0])

    return 0


