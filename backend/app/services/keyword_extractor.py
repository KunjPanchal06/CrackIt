def _term_in_text(term: str, text: str) -> bool:
    """Check if a term appears in text, using word boundaries for single words."""
    if len(term.split()) > 1:
        return term in text
    return bool(re.search(r'\b' + re.escape(term) + r'\b', text))


def _get_canonical(term: str) -> str:
    """
    Given a keyword (possibly a synonym), return the canonical form.
    If not in the synonym map, returns the term itself lowercased.
    """
    term_lower = term.lower().strip()

    if term_lower in SYNONYM_MAP:
        return term_lower

    for canonical, synonyms in SYNONYM_MAP.items():
        if term_lower in [s.lower() for s in synonyms]:
            return canonical.lower()

    return term_lower


def _keyword_found_in_text(keyword: str, text_lower: str) -> bool:
    """
    Check if a keyword (or any of its synonyms) appears in the text.
    """
    # Collect all forms: canonical + synonyms
    forms_to_check = {keyword.lower()}

    kw_lower = keyword.lower()
    if kw_lower in SYNONYM_MAP:
        forms_to_check.update(s.lower() for s in SYNONYM_MAP[kw_lower])

    for canonical, synonyms in SYNONYM_MAP.items():
        if kw_lower in [s.lower() for s in synonyms]:
            forms_to_check.add(canonical.lower())
            forms_to_check.update(s.lower() for s in synonyms)

    # Check each form
    for form in forms_to_check:
        if len(form.split()) > 1:
            if form in text_lower:
                return True
        else:
            escaped = re.escape(form)
            if re.search(r'\b' + escaped + r'\b', text_lower):
                return True
            # Fallback for special chars (c++, c#, .net)
            if form in text_lower:
                return True

    return False


def _classify_keyword(keyword: str, jd_lower: str) -> str:
    """
    Classify a keyword as 'required' or 'preferred' based on
    proximity to signal phrases in the JD text.

    Default is 'required' — only reclassified if found near
    a preferred-signal AND not also near a required-signal.
    """
    kw_lower = keyword.lower()

    # Find all positions of this keyword (including synonym forms)
    kw_positions = []
    forms = {kw_lower}
    if kw_lower in SYNONYM_MAP:
        forms.update(s.lower() for s in SYNONYM_MAP[kw_lower])
    for canonical, synonyms in SYNONYM_MAP.items():
        if kw_lower in [s.lower() for s in synonyms]:
            forms.add(canonical.lower())
            forms.update(s.lower() for s in synonyms)

    for form in forms:
        kw_positions.extend(m.start() for m in re.finditer(re.escape(form), jd_lower))

    if not kw_positions:
        return "required"

    # Check if ANY occurrence is near a preferred signal
    near_preferred = False
    near_required = False

    for signal in PREFERRED_SIGNALS:
        for sig_pos in (m.start() for m in re.finditer(re.escape(signal), jd_lower)):
            for kw_pos in kw_positions:
                if abs(kw_pos - sig_pos) < 200:
                    near_preferred = True

    for signal in REQUIRED_SIGNALS:
        for sig_pos in (m.start() for m in re.finditer(re.escape(signal), jd_lower)):
            for kw_pos in kw_positions:
                if abs(kw_pos - sig_pos) < 200:
                    near_required = True

    # Only classify as preferred if near a preferred signal
    # AND NOT also near a required signal
    if near_preferred and not near_required:
        return "preferred"

    return "required"
